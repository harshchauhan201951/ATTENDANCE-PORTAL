-- RACER साथी teacher escalation inbox. Service-role API writes these rows;
-- teacher-facing screens can filter open rows by teacher_name.
create table if not exists public.student_support_requests (
  id bigint generated by default as identity primary key,
  student_id bigint not null,
  student_name text,
  student_username text,
  class_name text,
  teacher_name text,
  teacher_contact text,
  message text not null,
  audio_url text,
  status text not null default 'open' check (status in ('open','in_progress','resolved')),
  created_at timestamptz not null default now(),
  resolved_at timestamptz,
  resolved_by text
);

create index if not exists student_support_requests_open_idx
  on public.student_support_requests (status, teacher_name, created_at desc);

alter table public.student_support_requests enable row level security;
