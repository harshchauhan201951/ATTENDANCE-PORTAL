import jsPDF from "jspdf";
import type { MonthlyResultSnapshot } from "./monthly-result";

const INK: [number, number, number] = [18, 34, 58];
const MUTED: [number, number, number] = [105, 120, 141];
const GOLD: [number, number, number] = [191, 148, 72];
const PALE: [number, number, number] = [244, 247, 251];
const LINE: [number, number, number] = [222, 229, 238];

function dateLabel(value: string) {
  if (!value) return "—";
  const date = new Date(`${String(value).slice(0, 10)}T00:00:00`);
  return Number.isNaN(date.getTime()) ? value : date.toLocaleDateString("en-IN");
}

/** Shared premium monthly-result statement used by teacher and student downloads. */
export function buildMonthlyResultPdf(snapshot: MonthlyResultSnapshot) {
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const width = doc.internal.pageSize.getWidth();
  const height = doc.internal.pageSize.getHeight();
  const left = 15;
  const right = width - 15;
  let y = 0;

  const chrome = (pageTitle: string) => {
    doc.setFillColor(...INK);
    doc.rect(0, 0, width, 39, "F");
    doc.setFillColor(...GOLD);
    doc.rect(0, 39, width, 1.4, "F");
    doc.setTextColor(255, 255, 255);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(17);
    doc.text("RACER ACADEMY", left, 15);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(218, 226, 238);
    doc.text("ACADEMIC PERFORMANCE OFFICE  ·  MONTHLY STATEMENT", left, 22);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(9);
    doc.setTextColor(255, 255, 255);
    doc.text(pageTitle.toUpperCase(), right, 15, { align: "right" });
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.text(snapshot.monthLabel.toUpperCase(), right, 22, { align: "right" });
    y = 48;
  };
  const footer = () => {
    const pages = doc.getNumberOfPages();
    for (let page = 1; page <= pages; page++) {
      doc.setPage(page);
      doc.setDrawColor(...LINE);
      doc.line(left, height - 15, right, height - 15);
      doc.setFont("helvetica", "normal");
      doc.setFontSize(7);
      doc.setTextColor(...MUTED);
      doc.text("CONFIDENTIAL STUDENT RECORD  ·  Generated by RACER ACADEMY", left, height - 10);
      doc.text(`${page} / ${pages}`, right, height - 10, { align: "right" });
    }
  };
  const newPage = (title: string) => { doc.addPage(); chrome(title); };
  const ensure = (space: number, title: string) => {
    if (y + space > height - 22) newPage(title);
  };
  const sectionTitle = (label: string) => {
    ensure(14, label);
    doc.setFillColor(...PALE);
    doc.roundedRect(left, y - 5, right - left, 10, 2, 2, "F");
    doc.setFillColor(...GOLD);
    doc.rect(left, y - 5, 1.2, 10, "F");
    doc.setFont("helvetica", "bold");
    doc.setFontSize(9);
    doc.setTextColor(...INK);
    doc.text(label.toUpperCase(), left + 4, y + 1);
    y += 13;
  };
  const wrapped = (value: unknown, maxWidth: number) => doc.splitTextToSize(String(value ?? "—"), maxWidth) as string[];

  chrome("Monthly Academic Report");
  doc.setTextColor(...MUTED);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(8);
  doc.text("STUDENT PERFORMANCE DOSSIER", left, y);
  y += 8;
  doc.setTextColor(...INK);
  doc.setFontSize(21);
  doc.text(wrapped(snapshot.student.name || "Student", 175), left, y);
  y += Math.max(8, wrapped(snapshot.student.name || "Student", 175).length * 8);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(...MUTED);
  doc.text(`${snapshot.student.className || "Class not assigned"}  ·  ${snapshot.monthLabel}  ·  Session ${snapshot.student.academicSession || "—"}`, left, y);
  y += 9;

  const cardY = y;
  doc.setFillColor(...INK);
  doc.roundedRect(left, cardY, right - left, 29, 3, 3, "F");
  const metrics = [
    ["OVERALL SCORE", `${snapshot.totals.grandObtained} / ${snapshot.totals.grandTotal}`],
    ["PERCENTAGE", `${snapshot.totals.percentage.toFixed(2)}%`],
    ["FINAL RESULT", snapshot.totals.status],
  ];
  metrics.forEach(([label, value], index) => {
    const x = left + 7 + index * 58;
    doc.setFont("helvetica", "normal"); doc.setFontSize(7); doc.setTextColor(202, 213, 230); doc.text(label, x, cardY + 9);
    doc.setFont("helvetica", "bold"); doc.setFontSize(index === 2 ? 12 : 14); doc.setTextColor(255, 255, 255); doc.text(value, x, cardY + 20);
  });
  y += 37;

  sectionTitle("Student Profile");
  const profile = [
    ["Father / Guardian", snapshot.student.fatherName || "—", "Roll Number", snapshot.student.rollNo || "—"],
    ["Student ID", String(snapshot.student.id), "Medium", snapshot.student.medium || "—"],
  ];
  for (const [labelA, valueA, labelB, valueB] of profile) {
    doc.setFontSize(8); doc.setFont("helvetica", "bold"); doc.setTextColor(...MUTED); doc.text(labelA, left + 2, y);
    doc.setFont("helvetica", "normal"); doc.setTextColor(...INK); doc.text(wrapped(valueA, 51), left + 35, y);
    doc.setFont("helvetica", "bold"); doc.setTextColor(...MUTED); doc.text(labelB, left + 96, y);
    doc.setFont("helvetica", "normal"); doc.setTextColor(...INK); doc.text(wrapped(valueB, 45), left + 126, y);
    y += 7;
  }
  y += 4;

  const table = (title: string, rows: Array<{ name: string; subject?: string; date: string; obtained: number; total: number; percentage: number }>) => {
    sectionTitle(title);
    const col = [left + 2, left + 82, left + 119, left + 148];
    const head = () => {
      doc.setFillColor(...INK); doc.roundedRect(left, y - 4, right - left, 8, 1.5, 1.5, "F");
      doc.setFont("helvetica", "bold"); doc.setFontSize(7); doc.setTextColor(255, 255, 255);
      ["ASSESSMENT", "SUBJECT", "DATE", "SCORE / %"].forEach((v, i) => doc.text(v, col[i], y + 1));
      y += 8;
    };
    head();
    if (!rows.length) {
      doc.setFont("helvetica", "normal"); doc.setFontSize(8); doc.setTextColor(...MUTED);
      doc.text("No eligible assessment recorded for this period.", left + 2, y + 2); y += 8; return;
    }
    rows.forEach((row, index) => {
      const nameLines = wrapped(row.name || "—", 75);
      const subjectLines = wrapped(row.subject || "—", 34);
      const rowHeight = Math.max(nameLines.length, subjectLines.length, 1) * 4 + 3;
      if (y + rowHeight > height - 23) { newPage(`${title} · continued`); sectionTitle(`${title} · continued`); head(); }
      if (index % 2 === 0) { doc.setFillColor(249, 250, 252); doc.rect(left, y - 3, right - left, rowHeight, "F"); }
      doc.setFont("helvetica", "normal"); doc.setFontSize(7.5); doc.setTextColor(...INK);
      doc.text(nameLines, col[0], y); doc.text(subjectLines, col[1], y); doc.text(dateLabel(row.date), col[2], y);
      doc.setFont("helvetica", "bold"); doc.text(`${row.obtained}/${row.total}  ·  ${row.percentage.toFixed(1)}%`, col[3], y);
      y += rowHeight;
    });
    y += 5;
  };

  table("Quiz Performance", snapshot.quizzes.map((q) => ({ name: q.title, subject: q.subject, date: q.date, obtained: q.obtained, total: q.total, percentage: q.percentage })));
  table("Saturday Weekly Tests", snapshot.weeklyTests.map((t) => ({ name: t.name, subject: t.subject, date: t.date, obtained: t.obtained, total: t.total, percentage: t.percentage })));

  sectionTitle("Monthly MahaTest");
  const maha = [
    ["Assessment date", dateLabel(snapshot.mahaTest.date)], ["Duration", `${snapshot.mahaTest.durationMinutes} minutes`],
    ["Maximum marks", String(snapshot.mahaTest.total)], ["Obtained marks", snapshot.mahaTest.obtained === null ? "Pending" : String(snapshot.mahaTest.obtained)],
  ];
  doc.setFontSize(8);
  maha.forEach(([label, value], index) => {
    const x = left + (index % 2) * 88;
    if (index % 2 === 0 && index > 0) y += 9;
    doc.setFont("helvetica", "bold"); doc.setTextColor(...MUTED); doc.text(label, x, y);
    doc.setFont("helvetica", "normal"); doc.setTextColor(...INK); doc.text(value, x + 34, y);
  });
  y += 10;
  if (snapshot.mahaTest.remarks) {
    ensure(14, "Teacher Remarks"); sectionTitle("Teacher Remarks");
    doc.setFont("helvetica", "normal"); doc.setFontSize(8); doc.setTextColor(...INK);
    const lines = wrapped(snapshot.mahaTest.remarks, right - left - 4); doc.text(lines, left + 2, y); y += lines.length * 4 + 5;
  }

  sectionTitle("Final Calculation");
  const calculations = [
    ["Quiz marks", `${snapshot.totals.quizObtained} / ${snapshot.totals.quizTotal}`],
    ["Weekly test marks", `${snapshot.totals.weeklyObtained} / ${snapshot.totals.weeklyTotal}`],
    ["MahaTest marks", `${snapshot.totals.mahaObtained} / ${snapshot.totals.mahaTotal}`],
    ["Pass threshold", `${snapshot.totals.passPercentage}%`],
  ];
  calculations.forEach(([label, value], index) => {
    ensure(8, "Final Calculation");
    if (index % 2 === 0) { doc.setFillColor(...PALE); doc.rect(left, y - 4, right - left, 7, "F"); }
    doc.setFont("helvetica", "normal"); doc.setFontSize(8); doc.setTextColor(...INK); doc.text(label, left + 2, y);
    doc.setFont("helvetica", "bold"); doc.text(value, right - 2, y, { align: "right" }); y += 7;
  });
  if (snapshot.position || snapshot.award) {
    y += 3;
    const recognition = [snapshot.position ? `Class position: ${snapshot.position}` : "", snapshot.award ? `Award: ${snapshot.awardGroup ? `${snapshot.award} (${snapshot.awardGroup})` : snapshot.award}` : ""].filter(Boolean).join("   ·   ");
    ensure(10, "Recognition"); doc.setTextColor(...GOLD); doc.setFont("helvetica", "bold"); doc.setFontSize(9); doc.text(wrapped(recognition, right - left), left + 2, y); y += 8;
  }
  footer();
  return doc;
}
