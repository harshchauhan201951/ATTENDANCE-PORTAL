-- Teacher inbox for student activity and quiz submission notifications.
create table if not exists public.teacher_notifications (
  id bigint generated by default as identity primary key,
  teacher_id bigint not null references public.teachers(id) on delete cascade,
  title text not null,
  message text not null,
  category text not null default 'general',
  url text not null default '/teacher/dashboard',
  metadata jsonb not null default '{}'::jsonb,
  is_read boolean not null default false,
  read_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists teacher_notifications_teacher_created_idx
  on public.teacher_notifications (teacher_id, created_at desc);
create index if not exists teacher_notifications_teacher_unread_idx
  on public.teacher_notifications (teacher_id, is_read, created_at desc);

alter table public.teacher_notifications enable row level security;
